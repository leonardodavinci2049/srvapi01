  `ANO` int(11) NOT NULL,
  `SERIE` int(11) NOT NULL,
  `NUMERO_INICIAL` int(11) NOT NULL,
  `NUMERO_FINAL` int(11) NOT NULL,
  `QUANTIDADE` int(11) NOT NULL,
  `BLOCO_ATUAL` int(11) NOT NULL DEFAULT 1,
  `TOTAL_BLOCOS` int(11) NOT NULL DEFAULT 1,
