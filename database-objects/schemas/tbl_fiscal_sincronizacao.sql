CREATE TABLE `tbl_fiscal_sincronizacao` (
  `ID_TBL_FISCAL_SINCRONIZACAO` bigint(20) NOT NULL AUTO_INCREMENT,
  `ID_SYSTEM_CLIENTE` int(11) NOT NULL,
  `CNPJ_EMITENTE` varchar(14) NOT NULL,
  `TIPO_DOCUMENTO` varchar(10) NOT NULL,
  `DATA_INICIAL` date DEFAULT NULL,
  `DATA_FINAL` date DEFAULT NULL,
  `HASH_PROXIMA_PAGINA` varchar(200) DEFAULT NULL,
  `STATUS` varchar(30) NOT NULL DEFAULT 'PENDENTE' COMMENT 'PENDENTE, PROCESSANDO, CONCLUIDO, ERRO',
  `TOTAL_RETORNADAS` int(11) NOT NULL DEFAULT 0,
  `TOTAL_INSERIDAS` int(11) NOT NULL DEFAULT 0,
  `TOTAL_ATUALIZADAS` int(11) NOT NULL DEFAULT 0,
  `TOTAL_DUPLICADAS` int(11) NOT NULL DEFAULT 0,
  `TOTAL_IGNORADAS` int(11) NOT NULL DEFAULT 0,
  `MENSAGEM` text DEFAULT NULL,
  `DT_INICIO` datetime DEFAULT NULL,
  `DT_FIM` datetime DEFAULT NULL,
  `DT_CADASTRO` datetime NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`ID_TBL_FISCAL_SINCRONIZACAO`),
  KEY `IDX_FISCAL_SYNC_EMPRESA` (`ID_SYSTEM_CLIENTE`,`CNPJ_EMITENTE`,`TIPO_DOCUMENTO`,`DT_CADASTRO`),
  KEY `IDX_FISCAL_SYNC_STATUS` (`ID_SYSTEM_CLIENTE`,`STATUS`,`DT_CADASTRO`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
