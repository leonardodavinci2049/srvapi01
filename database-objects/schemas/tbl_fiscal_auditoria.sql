CREATE TABLE `tbl_fiscal_auditoria` (
  `ID_TBL_FISCAL_AUDITORIA` bigint(20) NOT NULL AUTO_INCREMENT,
  `ID_TBL_FISCAL_EMISSAO` bigint(20) DEFAULT NULL,
  `ID_SYSTEM_CLIENTE` int(11) NOT NULL,
  `CNPJ_EMITENTE` varchar(14) NOT NULL,
  `TIPO_DOCUMENTO` varchar(10) NOT NULL,
  `ID_INTEGRACAO` varchar(80) DEFAULT NULL,
  `ID_PLUGNOTAS` varchar(80) DEFAULT NULL,
  `TIPO_AUDITORIA` varchar(40) NOT NULL COMMENT 'PRE_TRANSMISSAO, POS_RETORNO, SINCRONIZACAO, CONTADOR',
  `RESULTADO` varchar(20) NOT NULL COMMENT 'OK, AVISO, ERRO, BLOQUEADO',
  `QTD_ERROS` int(11) NOT NULL DEFAULT 0,
  `QTD_AVISOS` int(11) NOT NULL DEFAULT 0,
  `MENSAGEM` text DEFAULT NULL,
  `DETALHE` longtext DEFAULT NULL,
  `DT_AUDITORIA` datetime NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`ID_TBL_FISCAL_AUDITORIA`),
  KEY `IDX_FISCAL_AUD_EMISSAO` (`ID_TBL_FISCAL_EMISSAO`,`DT_AUDITORIA`),
  KEY `IDX_FISCAL_AUD_EMPRESA` (`ID_SYSTEM_CLIENTE`,`CNPJ_EMITENTE`,`TIPO_DOCUMENTO`,`DT_AUDITORIA`),
  KEY `IDX_FISCAL_AUD_RESULTADO` (`ID_SYSTEM_CLIENTE`,`RESULTADO`,`DT_AUDITORIA`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
